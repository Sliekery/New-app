  /* Scale a drawing up to fill its frame.
   *
   * The art box is -1..1, but a composition rarely lands on those bounds — a
   * trooper drawn between -0.66 and 0.66 renders a third smaller than a shield
   * drawn to the edge, and side by side in a grid the small ones read as
   * unfinished rather than as distant. Fitting each drawing to the frame means
   * the subject is the same size on every card whatever it happens to be, and
   * it costs nothing at authoring time. Cached: the maths is per-drawing, not
   * per-render, and a card is re-rendered constantly. */
  var fitted = {};
  function fitToFrame(art, key) {
    if (fitted[key]) return fitted[key];
    var lo = 9, hi = -9, i, j, p;
    for (i = 0; i < art.p.length; i++) {
      for (j = 0; j < art.p[i].length; j++) { p = art.p[i][j]; if (p < lo) lo = p; if (p > hi) hi = p; }
    }
    (art.e || []).forEach(function (e) {
      for (j = 0; j < 2; j++) { if (e[j] < lo) lo = e[j]; if (e[j] > hi) hi = e[j]; }
    });
    var span = Math.max(hi, -lo);
    // only ever grow, and never past the box: a drawing already at the edge is
    // left exactly as it was authored
    var k = (span > 0.05 && span < 0.94) ? 0.94 / span : 1;
    if (k === 1) { fitted[key] = art; return art; }
    var out = { p: art.p.map(function (l) { return l.map(function (v) { return Math.round(v * k * 1000) / 1000; }); }) };
    if (art.e) out.e = art.e.map(function (e) { return [e[0] * k, e[1] * k]; });
    if (art.m) out.m = art.m.map(function (v) { return v * k; });
    fitted[key] = out;
    return out;
  }

