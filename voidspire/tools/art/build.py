"""Runs every sprite generator in this folder and writes js/enemyart.js.
Usage: python3 tools/art/build.py [id ...]   (no ids: all of them)
Coordinates are rounded to 2 decimals: a hundredth of the -1..1 box is under a pixel at every size an enemy is
drawn, and it halves the file next to 3 decimals."""
import importlib.util, json, os, sys, glob

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "js", "enemyart.js")

def load(path):
    spec = importlib.util.spec_from_file_location(os.path.basename(path)[:-3], path)
    m = importlib.util.module_from_spec(spec)
    sys.path.insert(0, HERE)
    spec.loader.exec_module(m)
    return m

def r2(v):
    v = round(v, 2)
    return 0 if v == 0 else (int(v) if v == int(v) else v)

def build_one(m, fn=None):
    fn = fn or m.frame
    frames = []
    for i in range(m.N):
        f = fn(i, m.N)
        frames.append({"p": [[r2(v) for v in p] for p in f["p"]],
                       "e": [[r2(e[0]), r2(e[1])] + ([round(e[2], 3)] if len(e) > 2 else []) for e in f.get("e", [])]})
    return {"fps": m.FPS, "frames": frames}

mods = []
for path in sorted(glob.glob(os.path.join(HERE, "*.py"))):
    if os.path.basename(path) in ("lib.py", "build.py"):
        continue
    m = load(path)
    mods.append((m.ID, m, (m.__doc__ or "").strip()))

lines = ["/* =========================================================================",
         " * VOIDSPIRE — enemyart.js  (GENERATED by tools/art/build.py — do not edit)",
         " * Animated art for the enemies. Each entry is an idle reel {fps, frames}",
         " * made by a generator in tools/art/<id>.py, which builds one drawing and",
         " * turns its joints frame by frame, so every frame is the same creature.",
         " * Loaded after enemies.js; an entry here replaces that enemy's `art`.",
         " * ========================================================================= */",
         "(function (ns) {", "  'use strict';", "  var A = {}, ALT = {};"]
total = 0
for eid, m, doc in mods:
    data = json.dumps(build_one(m), separators=(",", ":"))
    total += len(data)
    first = doc.split("\n")[0] if doc else eid
    lines.append("  // " + first)
    lines.append("  A." + eid + " = " + data + ";")
    if hasattr(m, "frame_alt"):              # a second model, picked per spawn (engine.js reads artAlt)
        alt = json.dumps(build_one(m, m.frame_alt), separators=(",", ":"))
        total += len(alt)
        lines.append("  ALT." + eid + " = " + alt + ";")
lines += ["  Object.keys(A).forEach(function (id) {",
          "    var e = ns.ENEMIES && ns.ENEMIES[id];",
          "    if (!e) return;",
          "    e.art = A[id];",
          "    if (ALT[id]) e.artAlt = ALT[id]; else delete e.artAlt;",
          "  });",
          "  ns.ENEMY_ART = A;",
          "})(typeof window !== 'undefined' ? (window.VS = window.VS || {}) : (global.VS = global.VS || {}));", ""]
open(OUT, "w").write("\n".join(lines))
print(f"wrote {len(mods)} sprites, {total // 1024} KB -> js/enemyart.js")
