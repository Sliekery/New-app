/* =========================================================================
 * Build LINEWORK — the artist tool as one file anybody can open.
 *
 * WHY A BUILD SCRIPT AND NOT A COPY. A fork would be out of date by the end
 * of the week: the artist has taken sixteen builds so far and every fix would
 * have to be made twice, which in practice means made once and forgotten in
 * the other. tools/artist.html stays the only source. This produces the
 * standalone from it, so the gift keeps up with the tool for free.
 *
 * WHAT IT CHANGES, and no more:
 *
 *   1. Drops <script src="assets.js">, the game's 346 pieces of art. That is
 *      the ONLY external file the artist loads, so removing it is what makes
 *      the output genuinely one file — open it from a folder, from a phone,
 *      from an email attachment, offline, no server.
 *   2. Renames it. VOIDSPIRE means nothing to somebody who has not played it.
 *   3. Appends a shim that hides the parts that only make sense inside this
 *      project, rewrites the game-facing wording, and adds SAVE SVG and
 *      SAVE PNG — because a drawing tool whose only output is a block of
 *      JavaScript for js/enemies.js is not a drawing tool to anyone else.
 *
 * The shim is APPENDED rather than surgically spliced into the tool's own
 * code. Regex surgery on 1800 lines of somebody else's markup breaks the
 * moment a line is reformatted; a shim that runs after the page is built
 * touches only the ids it names, and if one of those ever disappears it does
 * nothing rather than something wrong. The two edits that could not be done
 * that way — the script tag and the export prefix — are asserted before they
 * are made, so a rename fails the build loudly instead of shipping silently
 * broken.
 *
 * Run:  node tools/build-standalone.js
 * Out:  tools/linework.html
 * ========================================================================= */
'use strict';
var fs = require('fs'), path = require('path');

var NAME = 'LINEWORK';
var TAG = 'a small tool for drawing with lines';

var src = fs.readFileSync(path.join(__dirname, 'artist.html'), 'utf8');
function must(find, replace, what) {
  if (src.indexOf(find) < 0) {
    console.error('build-standalone: could not find ' + what);
    console.error('  looked for: ' + JSON.stringify(find.slice(0, 90)));
    process.exit(1);
  }
  src = src.split(find).join(replace);
}

// 1. the one external file
must('<script src="assets.js"></script>\n', '', 'the assets.js script tag');

// 2. the name
must('<title>VOIDSPIRE · ARTIST</title>', '<title>' + NAME + '</title>', 'the title');
must('<h1>VOIDSPIRE · ARTIST <span>— sketch, trace, animate, paste it in · <b id="ver"></b></span></h1>',
  '<h1>' + NAME + ' <span>— ' + TAG + ' · <b id="ver"></b></span></h1>', 'the heading');

/* 3. the export prefix. `art: { … },` is the shape js/enemies.js wants — a
 * property in an object literal, comma and all. On its own it reads as a
 * syntax error somebody forgot to finish. LOAD FROM BOX already strips an
 * optional `art:` and a trailing comma, so dropping both here still round
 * trips. */
must("out.value = 'art: ' + block(0) + ',';", "out.value = block(0);", 'the single-frame export');
must("out.value = 'art: { fps: ' + doc.fps + ', frames: [\\n  ' + fr.join(',\\n  ') + '\\n] },';",
  "out.value = '{ fps: ' + doc.fps + ', frames: [\\n  ' + fr.join(',\\n  ') + '\\n] }';",
  'the animation export');

var SHIM = `
<script>
/* =========================================================================
 * LINEWORK — the standalone shim.
 * Everything below runs after the tool has built itself, and only touches
 * things by id or by the text of a heading. Generated by
 * tools/build-standalone.js; do not edit this file, edit that one.
 * ========================================================================= */
(function () {
  'use strict';

  function boxWithHeading(text) {
    var hs = document.querySelectorAll('.box h2');
    for (var i = 0; i < hs.length; i++) {
      if (hs[i].textContent.indexOf(text) >= 0) return hs[i].closest('.box');
    }
    return null;
  }
  function gone(el) { if (el) el.style.display = 'none'; }
  function reword(sel, html) { var e = document.querySelector(sel); if (e) e.innerHTML = html; }

  // the game's own art, and the button that hands work back to the project
  gone(boxWithHeading("THE GAME'S ART"));
  gone(document.getElementById('vsHandoff'));

  // wording that only means something inside the game it came from
  var lay = boxWithHeading('LAYERS');
  if (lay) {
    var hint = lay.querySelector('p.hint');
    if (hint) hint.innerHTML = 'The <b>eye</b> column shows a layer; the <b>&#9670;</b> '
      + 'column decides whether it is <b>saved out</b>. Turn &#9670; off on a sketch layer '
      + 'and it stays a guide you can see but never export.';
  }
  /* The preview panel draws the art at the three sizes the game uses, which
   * is genuinely useful anywhere — but its FIGURE / FRAME toggle is about a
   * UI-frame slot that does not exist outside the game, and "ONE CORNER"
   * means nothing without it. */
  var pv = boxWithHeading('LIVE PREVIEW');
  if (pv) {
    var pvh = pv.querySelector('h2');
    if (pvh) pvh.textContent = 'LIVE PREVIEW \u2014 how it reads at real sizes';
    var toggle = document.getElementById('pvFig');
    if (toggle && toggle.parentNode) toggle.parentNode.style.display = 'none';
  }

  var outBox = boxWithHeading('THE ART BLOCK');
  if (outBox) {
    /* OPEN HERE, whatever the tool folds by default. In the artist the export
     * block is a code block used once at the end of a session, so folding it
     * is right. In this build it holds SAVE SVG, which is the whole reason
     * the file exists — folded away, the first thing a stranger looks for is
     * behind a heading they have no reason to click. */
    if (outBox.classList.contains('shut')) {
      var head = outBox.querySelector('h2');
      if (head && head.onclick) head.onclick();
      else outBox.classList.remove('shut');
    }
    var h2 = outBox.querySelector('h2');
    if (h2) h2.textContent = 'THE DRAWING, AND HOW TO GET IT OUT';
    var p = outBox.querySelector('p.hint');
    if (p) p.innerHTML =
      '<b>SAVE SVG</b> is the one you want for anything else — it is line art at '
      + 'any size, opens in a browser, and drops into Illustrator, Inkscape, Figma '
      + 'or a web page. An animation saves as an SVG that plays on its own.<br>'
      + '<b>SAVE PNG</b> is a picture of it as you see it here; more than one frame '
      + 'saves as a strip.<br>'
      + '<b>SAVE .JSON</b> keeps your layers and frames so you can carry on later '
      + '\\u2014 the box above alone cannot. The box is the drawing as plain numbers, '
      + 'and <b>LOAD FROM BOX</b> reads it back.';
  }

  /* ---- SVG and PNG -----------------------------------------------------
   * Both are built from the export box rather than from the canvas on
   * screen, which carries a grid, a mirror line and point handles that
   * nobody wants in their picture. The box is also the tool's tested
   * contract, so this cannot drift from what the tool thinks it drew. */
  function drawing() {
    var t = (document.getElementById('out').value || '').trim()
      .replace(/^art:\\s*/, '').replace(/,\\s*$/, '');
    if (!t) return null;
    try { return (new Function('return (' + t + ')'))(); } catch (e) { return null; }
  }
  function frames(d) { return (d && d.frames) ? d.frames : (d ? [d] : []); }
  function save(blob, name) {
    var a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = name;
    a.click();
    setTimeout(function () { URL.revokeObjectURL(a.href); }, 4000);
  }
  function stamp() {
    var n = (document.querySelector('.layer-name') || {}).textContent;
    return 'drawing-' + new Date().toISOString().slice(0, 10);
  }

  /* The art lives in a -1..1 box. A hair of margin keeps a stroke that runs
   * to the very edge from being sliced in half by its own line width. */
  var VB = '-1.08 -1.08 2.16 2.16';
  function svgShapes(f, dx) {
    var s = '', shift = dx ? ' transform="translate(' + dx + ',0)"' : '';
    var g = '<g' + shift + '>';
    (f.p || []).forEach(function (q) {
      var pts = [];
      for (var i = 0; i < q.length; i += 2) pts.push(q[i] + ',' + q[i + 1]);
      g += '<polyline points="' + pts.join(' ') + '"/>';
    });
    (f.e || []).forEach(function (e) {
      g += '<circle class="eye" cx="' + e[0] + '" cy="' + e[1] + '" r="0.05"/>';
    });
    return g + '</g>' + s;
  }
  function toSVG(d) {
    var fr = frames(d);
    if (!fr.length) return null;
    var n = fr.length, fps = d.fps || 8;
    /* Stroke colour is currentColor with a colour set on the root, so the
     * file is black line art out of the box and one attribute away from any
     * other colour — including being recoloured by CSS once it is in a page. */
    var head = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="' + VB + '" '
      + 'width="512" height="512" color="#111">'
      + '<style>'
      + 'polyline{fill:none;stroke:currentColor;stroke-width:.045;'
      + 'stroke-linejoin:round;stroke-linecap:round}'
      + 'circle.eye{fill:currentColor;stroke:none}';
    if (n > 1) {
      /* An animation is written as a reel: the frames sit side by side and
       * the strip is stepped one frame-width at a time. It needs no script,
       * so it plays in an <img>, in a browser tab, in anything that renders
       * SVG at all — and a viewer that will not animate shows frame one
       * rather than every frame stacked on top of each other. */
      head += '.reel{animation:reel ' + (n / fps).toFixed(3) + 's steps(' + n + ') infinite}'
        + '@keyframes reel{to{transform:translateX(' + (-2.16 * n).toFixed(3) + 'px)}}'
        + '@media(prefers-reduced-motion:reduce){.reel{animation:none}}';
    }
    head += '</style>';
    if (n === 1) return head + svgShapes(fr[0], 0) + '</svg>';
    var body = '<g class="reel">';
    fr.forEach(function (f, i) { body += svgShapes(f, (2.16 * i).toFixed(3)); });
    return head + body + '</g></svg>';
  }

  function toPNG(d, cb) {
    var fr = frames(d);
    if (!fr.length) return cb(null);
    var S = 1024, n = fr.length;
    var c = document.createElement('canvas');
    c.width = S * n; c.height = S;
    var g = c.getContext('2d');
    // as it looks on screen, because a PNG is a picture of the drawing
    g.fillStyle = '#05090b'; g.fillRect(0, 0, c.width, c.height);
    fr.forEach(function (f, i) {
      g.save();
      g.translate(S * i + S / 2, S / 2);
      g.scale(S * 0.46, S * 0.46);
      g.strokeStyle = '#41d8ff';
      g.lineWidth = 4.5 / (S * 0.46);
      g.lineJoin = g.lineCap = 'round';
      (f.p || []).forEach(function (q) {
        if (q.length < 4) return;
        g.beginPath(); g.moveTo(q[0], q[1]);
        for (var k = 2; k < q.length; k += 2) g.lineTo(q[k], q[k + 1]);
        g.stroke();
      });
      g.fillStyle = '#f2fff5';
      (f.e || []).forEach(function (e) {
        g.beginPath(); g.arc(e[0], e[1], 0.05, 0, 7); g.fill();
      });
      g.restore();
    });
    c.toBlob(cb, 'image/png');
  }

  var bar = document.getElementById('bCopy') && document.getElementById('bCopy').parentNode;
  function addButton(label, cls, fn) {
    if (!bar) return;
    var b = document.createElement('button');
    b.textContent = label;
    if (cls) b.className = cls;
    b.onclick = fn;
    bar.insertBefore(b, bar.firstChild);
    return b;
  }
  function flash(b, msg) {
    var was = b.textContent;
    b.textContent = msg;
    setTimeout(function () { b.textContent = was; }, 1100);
  }
  var pngBtn = addButton('SAVE PNG', 'sm', function () {
    var d = drawing();
    if (!d) return alert('Draw something first.');
    var self = this;
    toPNG(d, function (blob) {
      if (!blob) return;
      var n = frames(d).length;
      save(blob, stamp() + (n > 1 ? '-' + n + 'frames' : '') + '.png');
      flash(self, 'SAVED');
    });
  });
  var svgBtn = addButton('SAVE SVG', null, function () {
    var d = drawing();
    if (!d) return alert('Draw something first.');
    var s = toSVG(d);
    if (!s) return alert('Draw something first.');
    save(new Blob([s], { type: 'image/svg+xml' }), stamp() + '.svg');
    flash(this, 'SAVED');
  });
  if (svgBtn) svgBtn.style.borderColor = '#5dff88';
  if (svgBtn) svgBtn.style.color = '#5dff88';

  /* MIRROR OFF BY DEFAULT. It is on in the tool it came from because every
   * enemy in that game is symmetric about the centre line, so drawing half a
   * robot and getting a whole one is exactly right there. To anybody else it
   * is a drawing program that draws two of everything, which reads as a bug
   * rather than a feature. It is still one button away. */
  try {
    var st = document.getElementById('status');
    var mir = document.getElementById('bMirror');
    if (mir && st && /MIRRORED/.test(st.textContent)) mir.click();
  } catch (e) {}

  /* A line saying what this is. It goes in the page rather than on the status
   * line, which the tool rewrites on its own next repaint — the note was there
   * and gone before anybody could read it. */
  var intro = document.createElement('p');
  intro.style.cssText = 'margin:0 0 9px;font-size:11px;line-height:1.6;color:#8fa79a;'
    + 'border-left:2px solid #5dff88;padding-left:9px';
  intro.innerHTML = 'Draw with the tools down the left \u2014 <b>PATH</b> taps out a line '
    + 'point by point, <b>FREE</b> draws by hand, <b>SHAPE</b> drags out one of nine. '
    + 'More than one frame makes it an animation. '
    + 'It saves itself in this browser as you go, and <b>SAVE SVG</b> at the bottom '
    + 'gets your drawing out as a file. '
    + '<a href="#" id="lwHide" style="color:#5dff88">hide this</a>';
  var h1 = document.querySelector('body > h1');
  if (h1 && h1.parentNode) h1.parentNode.insertBefore(intro, h1.nextSibling);
  try { if (localStorage.getItem('linework.introHidden')) intro.style.display = 'none'; } catch (e) {}
  var hideLink = document.getElementById('lwHide');
  if (hideLink) hideLink.onclick = function (ev) {
    ev.preventDefault();
    intro.style.display = 'none';
    try { localStorage.setItem('linework.introHidden', '1'); } catch (e) {}
  };
})();
</script>
`;

if (src.indexOf('</body>') < 0) { console.error('no </body>'); process.exit(1); }
src = src.replace('</body>', SHIM + '</body>');

var outPath = path.join(__dirname, 'linework.html');
fs.writeFileSync(outPath, src);

/* A standalone that quietly depends on a file is not standalone, and the way
 * that goes wrong is silent: the browser 404s the script and the page carries
 * on without it. So the check is here, at the moment the file is written,
 * rather than left to be noticed by whoever is sent it. */
var leftovers = src.match(/<(?:script|link|img)[^>]+(?:src|href)="(?!data:|https?:|#)[^"]+"/g);
if (leftovers) {
  console.error('build-standalone: the output still references files beside it:');
  leftovers.forEach(function (l) { console.error('  ' + l); });
  process.exit(1);
}

console.log('linework.html: ' + Math.round(src.length / 1024) + ' KB, one file, no dependencies');
